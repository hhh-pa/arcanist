use super::*;

#[test]
fn linter_name_is_generated() {
    assert_eq!(GeneratedLinter::new().name(), "GEN");
}

#[test]
fn detects_generated_marker() {
    assert!(is_generated(b"// @generated by protoc\n"));
    assert!(is_generated(b"/* @generated */"));
    assert!(is_generated(b"@generated"));
    assert!(is_generated(b"prefix @generated suffix"));
    // Case-sensitive, mirroring the PHP regex.
    assert!(!is_generated(b"@Generated"));
    assert!(!is_generated(b"generated without the at-sign"));
    assert!(!is_generated(b""));
    assert!(!is_generated(b"short"));
}

#[test]
fn linter_is_always_silent() {
    let linter = GeneratedLinter::new();
    assert!(linter.lint_bytes("f.txt", b"plain").is_empty());
    assert!(linter.lint_bytes("f.txt", b"// @generated\n").is_empty());
}
